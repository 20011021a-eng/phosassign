type Dict = (typeof copy)[Lang];

const Ctx = createContext<{ lang: Lang; t: Dict; toggle: () => void } | null>(null);

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>("zh");
  useEffect(() => {
    const saved = localStorage.getItem("phos-lang");
    if (saved === "en" || saved === "zh") setLang(saved);
  }, []);
  useEffect(() => {
    localStorage.setItem("phos-lang", lang);
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  }, [lang]);
  const value = useMemo(
    () => ({ lang, t: copy[lang], toggle: () => setLang((l) => (l === "zh" ? "en" : "zh")) }),
    [lang],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useLang() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("LangProvider missing");
  return ctx;
}
